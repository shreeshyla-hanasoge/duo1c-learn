#!/usr/bin/env bash
#
# Full deploy for learn.duo1c.in.
#
# Two passes are unavoidable: Vite bakes VITE_* into the bundle at BUILD
# time, but the Cognito and API values only exist after those stacks are
# created. So: deploy backend -> read outputs -> build -> deploy site.
#
#   ./scripts/deploy.sh                       # CloudFront URL only
#   ./scripts/deploy.sh --domain learn.duo1c.in --cert arn:aws:acm:us-east-1:...
#
set -euo pipefail

# macOS ships bash 3.2, where expanding an empty array under `set -u` is an
# error — hence the ${arr[@]+"${arr[@]}"} guard on every ctx expansion.

cd "$(dirname "$0")/.."

PROFILE="${AWS_PROFILE:-default}"
REGION="ap-south-1"
DOMAIN=""
CERT=""
GOOGLE_CLIENT_ID="${GOOGLE_CLIENT_ID:-}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --domain) DOMAIN="$2"; shift 2 ;;
    --cert)   CERT="$2";   shift 2 ;;
    --google-client-id) GOOGLE_CLIENT_ID="$2"; shift 2 ;;
    *) echo "unknown flag: $1" >&2; exit 1 ;;
  esac
done

ctx=()
[[ -n "$DOMAIN" ]] && ctx+=(-c "domainName=$DOMAIN")
[[ -n "$CERT" ]]   && ctx+=(-c "certificateArn=$CERT")
[[ -n "$GOOGLE_CLIENT_ID" ]] && ctx+=(-c "googleClientId=$GOOGLE_CLIENT_ID")

out() { # stack, key
  aws cloudformation describe-stacks --stack-name "$1" --region "$REGION" \
    --profile "$PROFILE" \
    --query "Stacks[0].Outputs[?OutputKey=='$2'].OutputValue" --output text 2>/dev/null
}

# Read the site URL BEFORE pass 1, not after: the Cognito callback list is
# written during pass 1, so learning the URL afterwards is a round too late and
# the CloudFront origin silently never becomes a valid redirect. Empty only on
# the very first run, which is what pass 3 exists to repair.
CF_URL="$(out LearnDuo1cSite CloudFrontUrl || true)"
[[ -n "$CF_URL" && "$CF_URL" != "None" ]] && ctx+=(-c "cloudfrontUrl=$CF_URL")

echo "==> Pass 1: data, auth, api"
( cd infra && AWS_PROFILE="$PROFILE" npx cdk deploy \
    LearnDuo1cData LearnDuo1cAuth LearnDuo1cApi \
    --require-approval never ${ctx[@]+"${ctx[@]}"} )

COGNITO_DOMAIN="$(out LearnDuo1cAuth CognitoDomain)"
CLIENT_ID="$(out LearnDuo1cAuth UserPoolClientId)"
API_URL="$(out LearnDuo1cApi ApiUrl)"
GOOGLE_ENABLED="$(out LearnDuo1cAuth GoogleEnabled)"

echo "==> Writing .env.production"
cat > .env.production <<EOF
# Generated by scripts/deploy.sh — do not edit by hand.
VITE_COGNITO_DOMAIN=$COGNITO_DOMAIN
VITE_COGNITO_CLIENT_ID=$CLIENT_ID
VITE_API_URL=$API_URL
VITE_GOOGLE_ENABLED=$GOOGLE_ENABLED
EOF
cat .env.production

echo "==> Building frontend"
npm run build

echo "==> Pass 2: site"
( cd infra && AWS_PROFILE="$PROFILE" npx cdk deploy LearnDuo1cSite \
    --require-approval never ${ctx[@]+"${ctx[@]}"} )

NEW_CF_URL="$(out LearnDuo1cSite CloudFrontUrl)"

# If the site URL was not known during pass 1, the Cognito client is missing
# it as a callback. Re-run auth/api once so sign-in works from CloudFront too.
if [[ "$CF_URL" != "$NEW_CF_URL" ]]; then
  echo "==> Pass 3: re-deploying auth/api with the site URL as a callback"
  ( cd infra && AWS_PROFILE="$PROFILE" npx cdk deploy \
      LearnDuo1cAuth LearnDuo1cApi --require-approval never \
      ${ctx[@]+"${ctx[@]}"} -c "cloudfrontUrl=$NEW_CF_URL" )
fi

echo
echo "Site:     $NEW_CF_URL"
[[ -n "$DOMAIN" ]] && echo "Domain:   https://$DOMAIN"
echo "API:      $API_URL"
echo "Cognito:  $COGNITO_DOMAIN"
echo "Google redirect URI: https://$COGNITO_DOMAIN/oauth2/idpresponse"
